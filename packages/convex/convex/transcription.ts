/**
 * A page of speaker-labelled segments. Needs `ViewTranscripts`.
 *
 * Rows are ordered by the session-relative `startMs` with `_creationTime` as
 * the stable tie-break, walked by an opaque index cursor. `seq` is per-speaker
 * and is not an ordering or paging key.
 */
export const listSegments = query({
  args: {
    sessionId: v.id("transcriptionSessions"),
    cursor: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const { userId } = await requireAuth(ctx);
    await requireTranscriptionUser(ctx, userId, Permission.ViewTranscripts);
    const session = await ctx.db.get(args.sessionId);
    if (session === null) {
      throw new ConvexError("Transcription session not found");
    }
    const result = await ctx.db
      .query("transcriptSegments")
      .withIndex("by_session_start", (q) => q.eq("sessionId", args.sessionId))
      .order("asc")
      .paginate({ cursor: args.cursor ?? null, numItems: SEGMENT_PAGE_SIZE });
    const page = [];
    for (const row of result.page) {
      const content = await segmentContent(row);
      page.push({
        id: row._id,
        seq: row.seq,
        speakerKey: row.speakerKey,
        speakerName: content.speakerName,
        text: content.text,
        startMs: row.startMs,
        endMs: row.endMs,
        confidence: row.confidence ?? null,
        language: row.language ?? null,
      });
    }
    return {
      page,
      nextCursor: result.isDone ? null : result.continueCursor,
    };
  },
});

/** Requests a (re)summary. Needs `ViewTranscripts`. */
export const requestSummary = mutation({
  args: { sessionId: v.id("transcriptionSessions") },
  handler: async (ctx, args) => {
    const { userId } = await requireAuth(ctx);
    await requireTranscriptionUser(ctx, userId, Permission.ViewTranscripts);
    const session = await ctx.db.get(args.sessionId);
    if (session === null) {
      throw new ConvexError("Transcription session not found");
    }
    if (session.status === "active") {
      throw new ConvexError("The call is still being transcribed");
    }
    if (session.status === "ending") {
      throw new ConvexError("Finishing the transcript; try again in a moment");
    }
    await enforceRateLimit(ctx, {
      key: userRateLimitKey("transcription-summary", userId),
      limit: SUMMARY_REQUEST_LIMIT,
      windowMs: SUMMARY_REQUEST_WINDOW_MS,
    });
    const config = await loadTranscriptionConfig(ctx);
    if (config === null || config.apiKeyCiphertext === undefined) {
      throw new ConvexError("Configure a summary endpoint first");
    }
    const now = Date.now();
    // A fresh pending attempt is already in flight; a second action would race
    // the first and could overwrite its result. The stale-recovery cron still
    // re-queues a lost pending attempt after the timeout.
    if (
      session.summaryStatus === "pending" &&
      session.summaryRequestedAt !== undefined &&
      now - session.summaryRequestedAt < SUMMARY_PENDING_STALE_MS
    ) {
      return null;
    }
    const attemptId = newSummaryAttemptId();
    await ctx.db.patch(session._id, {
      summaryStatus: "pending",
      summaryRequestedAt: now,
      summaryAttemptId: attemptId,
      summaryError: undefined,
    });
    await ctx.scheduler.runAfter(0, internal.transcriptionActions.summarize, {
      sessionId: session._id,
      attemptId,
    });
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.requestSummary",
      targetId: session._id,
    });
    return null;
  },
});

/** Deletes a transcript, its segments and its summary. Needs `ManageTranscription`. */
export const deleteSession = mutation({
  args: { sessionId: v.id("transcriptionSessions") },
  handler: async (ctx, args) => {
    const { userId } = await requireWorkspaceContext(ctx, Permission.ManageTranscription);
    await assertMayParticipate(ctx, userId);
    const session = await ctx.db.get(args.sessionId);
    if (session === null) {
      return null;
    }
    if (session.status === "active") {
      throw new ConvexError("Stop transcription before deleting it");
    }
    await ctx.db.delete(session._id);
    await ctx.scheduler.runAfter(0, internal.transcriptionCleanup.deleteSegments, {
      sessionId: session._id,
    });
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.delete",
      targetId: session._id,
    });
    return null;
  },
});

/** Summary regeneration is expensive; one caller cannot loop it. */
const SUMMARY_REQUEST_LIMIT = 5;
const SUMMARY_REQUEST_WINDOW_MS = 60_000;
/** A pending summary older than this is treated as lost and re-queued. */
const SUMMARY_PENDING_STALE_MS = 10 * 60_000;

/** True when an LLM endpoint/key is configured; only then is a summary queued. */
function summaryConfigured(config: Doc<"transcriptionConfig"> | null): boolean {
  return config !== null && config.apiKeyCiphertext !== undefined;
}

/** A fresh one-shot id for every queued summary attempt. */
function newSummaryAttemptId(): string {
  return randomToken(16);
}

/** Constant transcript page size; the cursor is opaque. */
const SEGMENT_PAGE_SIZE = 100;

/** Refresh the shared session aggregate at most this often per session. */
const SEGMENT_AGGREGATE_INTERVAL_MS = 30_000;
/** Bounded read of per-speaker state (one row per seated participant). */
const SPEAKER_STATE_LIMIT = 64;

interface SpeakerTotals {
  readonly segmentCount: number;
  readonly lastSeq: number;
}

async function speakerTotals(
  ctx: MutationCtx | QueryCtx,
  sessionId: Id<"transcriptionSessions">,
): Promise<SpeakerTotals> {
  const rows = await ctx.db
    .query("transcriptSpeakerState")
    .withIndex("by_session_speaker", (q) => q.eq("sessionId", sessionId))
    .take(SPEAKER_STATE_LIMIT);
  let segmentCount = 0;
  let lastSeq = 0;
  for (const row of rows) {
    segmentCount += row.segmentCount;
    lastSeq = Math.max(lastSeq, row.lastSeq);
  }
  return { segmentCount, lastSeq };
}

/**
 * Ingests finished segments posted by the transcriber. The HTTP route has
 * already checked the shared secret; this mutation re-validates that the
 * session is active and the speaker is really in the call.
 *
 * Replay protection is per `(session, speaker)`, not session-wide: the
 * transcriber starts each socket's sequence at 1, so concurrent speakers and a
 * reconnect must not conflict. Transcript order is `startMs`, never `seq`.
 */
export const ingestSegments = internalMutation({
  args: {
    sessionId: v.id("transcriptionSessions"),
    speakerKey: v.string(),
    segments: v.array(
      v.object({
        seq: v.number(),
        startMs: v.number(),
        endMs: v.number(),
        text: v.string(),
        confidence: v.optional(v.number()),
        language: v.optional(v.string()),
      }),
    ),
  },
  handler: async (ctx, args) => {
    if (args.segments.length === 0 || args.segments.length > TRANSCRIPTION_MAX_SEGMENTS_PER_BATCH) {
      throw new ConvexError("Invalid segment batch");
    }
    const server = await ctx.db.query("server").first();
    if (server?.settings.transcriptionEnabled !== true) {
      throw new ConvexError("Transcription is disabled");
    }
    const session = await ctx.db.get(args.sessionId);
    const ending = session !== null && session.status === "ending";
    if (session === null || (session.status !== "active" && !ending)) {
      throw new ConvexError("Transcription session is not active");
    }
    if (ending && (session.endsAt === undefined || Date.now() > session.endsAt)) {
      throw new ConvexError("The transcription finalization window has closed");
    }
    const call = await ctx.db.get(session.callId);
    // During finalization the call itself may already be ended and the seat
    // deleted; durable speaker authorization replaces the live seat check.
    if (call === null || (!ending && call.status === "ended")) {
      throw new ConvexError("This call has ended");
    }
    const speaker = parseTranscriptionSpeakerKey(args.speakerKey);
    if (speaker === null) {
      throw new ConvexError("Invalid speaker");
    }
    const state = await ctx.db
      .query("transcriptSpeakerState")
      .withIndex("by_session_speaker", (q) =>
        q.eq("sessionId", session._id).eq("speakerKey", args.speakerKey),
      )
      .unique();
    if (state?.blocked === true) {
      throw new ConvexError("Speaker was removed from this call");
    }
    let seated = false;
    if (!ending) {
      const seats = await ctx.db
        .query("callParticipants")
        .withIndex("by_call", (q) => q.eq("callId", call._id))
        .take(64);
      seated = seats.some((row) =>
        speaker.kind === "guest"
          ? row.guestId === speaker.id
          : row.userId === speaker.id && row.guestId === undefined,
      );
      if (!seated) {
        // A departure grace covers the transcriber's final window. A speaker
        // with no state row, or one who never left, is still rejected.
        if (state === null || state.leftAt === undefined) {
          throw new ConvexError("Speaker is not in this call");
        }
        if (Date.now() > state.leftAt + TRANSCRIPTION_SPEAKER_LEFT_GRACE_MS) {
          throw new ConvexError("The speaker's finalization window has closed");
        }
      }
    } else if (state === null) {
      // Never accept a speaker who was not authorized before the stop.
      throw new ConvexError("Speaker is not in this call");
    }
    // Rejoining clears the departure grace for the rest of this session.
    if (!ending && seated && state !== null && state.leftAt !== undefined) {
      await ctx.db.patch(state._id, { leftAt: undefined, updatedAt: Date.now() });
    }
    const departedAt = !ending && seated ? undefined : state?.leftAt;
    const first = args.segments[0];
    if (first === undefined) {
      throw new ConvexError("Invalid segment batch");
    }
    const stopRelative =
      ending && session.endedAt !== undefined
        ? Math.max(0, session.endedAt - session.startedAt)
        : null;
    const leftRelative =
      departedAt !== undefined ? Math.max(0, departedAt - session.startedAt) : null;
    for (let index = 0; index < args.segments.length; index += 1) {
      const segment = args.segments[index]!;
      const previous = args.segments[index - 1];
      if (
        !Number.isFinite(segment.seq) ||
        (previous !== undefined && segment.seq <= previous.seq)
      ) {
        throw new ConvexError("Segment sequence is out of order");
      }
      if (
        !Number.isFinite(segment.startMs) ||
        !Number.isFinite(segment.endMs) ||
        segment.startMs < 0 ||
        segment.endMs < segment.startMs ||
        segment.endMs - segment.startMs > MAX_SEGMENT_SPAN_MS
      ) {
        throw new ConvexError("Segment timestamps are invalid");
      }
      if (
        stopRelative !== null &&
        segment.startMs > stopRelative + TRANSCRIPTION_FINALIZE_TOLERANCE_MS
      ) {
        throw new ConvexError("Segment arrived after the session stopped");
      }
      if (
        leftRelative !== null &&
        segment.startMs > leftRelative + TRANSCRIPTION_FINALIZE_TOLERANCE_MS
      ) {
        throw new ConvexError("Segment arrived after the speaker left");
      }
    }
    // Per-speaker state is always a high-water mark: a batch can never lower
    // `lastSeq`, `lastStartMs` or the stored count.
    let lastSeq = state?.lastSeq ?? 0;
    let lastStartMs = state?.lastStartMs ?? -1;
    if (state !== null && first.seq <= state.lastSeq) {
      // A lower seq is a late arrival (for example an evicted socket's teardown
      // drain posted after a newer batch), an exact replay, or a transcriber
      // process restart whose counter began again at 1 after its clock moved
      // forward. A restart is accepted only when its whole range is strictly
      // after every stored segment for this speaker; otherwise the late/replay
      // check below decides. Sequence numbers are not a uniqueness key across a
      // restart (the counter genuinely restarted), so the forward check proves
      // newness by time instead; an exact replay is still blocked because its
      // range is no longer after the stored audio.
      const forward = await isForwardSpeakerBatch(
        ctx,
        session._id,
        args.speakerKey,
        first.startMs,
        state.lastStartMs,
        args.segments,
      );
      if (!forward) {
        await assertLateSegmentBatch(ctx, session._id, args.speakerKey, args.segments);
      }
    }
    for (const segment of args.segments) {
      lastSeq = Math.max(lastSeq, segment.seq);
      lastStartMs = Math.max(lastStartMs, segment.startMs);
    }
    const accepted = args.segments.filter(
      (segment) => segment.text.trim().slice(0, TRANSCRIPTION_MAX_SEGMENT_CHARS).length > 0,
    ).length;
    // A single speaker cannot exceed the whole-session cap; the shared session
    // aggregate is refreshed only periodically, so this per-speaker bound is
    // the hot-path enforcement.
    if ((state?.segmentCount ?? 0) + accepted > TRANSCRIPTION_MAX_SEGMENTS_PER_SESSION) {
      throw new ConvexError("This transcript reached its segment limit");
    }
    if (session.segmentCount + accepted > TRANSCRIPTION_MAX_SEGMENTS_PER_SESSION) {
      throw new ConvexError("This transcript reached its segment limit");
    }
    const speakerName = await resolveSpeakerName(ctx, args.speakerKey);
    let inserted = 0;
    for (const segment of args.segments) {
      const text = segment.text.trim().slice(0, TRANSCRIPTION_MAX_SEGMENT_CHARS);
      if (text.length === 0) {
        continue;
      }
      const id = await ctx.db.insert("transcriptSegments", {
        sessionId: session._id,
        seq: segment.seq,
        speakerKey: args.speakerKey,
        speakerNameCiphertext: "",
        textCiphertext: "",
        startMs: Math.trunc(segment.startMs),
        endMs: Math.trunc(segment.endMs),
        ...(segment.confidence !== undefined ? { confidence: segment.confidence } : {}),
        ...(segment.language !== undefined ? { language: segment.language.slice(0, 20) } : {}),
      });
      await ctx.db.patch(id, await sealSegment(id, speakerName, text));
      inserted += 1;
    }
    const now = Date.now();
    if (state === null) {
      await ctx.db.insert("transcriptSpeakerState", {
        sessionId: session._id,
        speakerKey: args.speakerKey,
        lastSeq,
        lastStartMs,
        segmentCount: inserted,
        updatedAt: now,
      });
    } else {
      await ctx.db.patch(state._id, {
        lastSeq,
        lastStartMs,
        segmentCount: state.segmentCount + inserted,
        updatedAt: now,
      });
    }
    // Refresh the shared aggregate at most once per interval so a busy call
    // does not write one hot document on every speaker's every batch.
    if (now - (session.countUpdatedAt ?? 0) >= SEGMENT_AGGREGATE_INTERVAL_MS) {
      const totals = await speakerTotals(ctx, session._id);
      await ctx.db.patch(session._id, {
        segmentCount: totals.segmentCount,
        lastSeq: Math.max(session.lastSeq, totals.lastSeq),
        countUpdatedAt: now,
      });
    }
    return { accepted: inserted };
  },
});

/** The longest single segment the transcriber may report (two minutes). */
const MAX_SEGMENT_SPAN_MS = 120_000;
/** Max rows sharing one seq: a call is capped at 50 seats, so this is ample. */
const MAX_REPLAY_SEQ_ROWS = 64;
/** Bound on stored rows scanned to prove a batch's range is disjoint. */
const MAX_OVERLAP_ROWS = 1_024;

/**
 * Whether a batch's session-relative range overlaps any stored segment for the
 * same speaker. Returns `null` when the bounded read cannot prove the answer so
 * callers fail closed (never store audio they could not check).
 */
async function storedSpeakerRangeOverlaps(
  ctx: MutationCtx,
  sessionId: Id<"transcriptionSessions">,
  speakerKey: string,
  segments: readonly { readonly startMs: number; readonly endMs: number }[],
): Promise<boolean | null> {
  let minStart = Number.POSITIVE_INFINITY;
  let maxEnd = Number.NEGATIVE_INFINITY;
  for (const segment of segments) {
    minStart = Math.min(minStart, segment.startMs);
    maxEnd = Math.max(maxEnd, segment.endMs);
  }
  // A stored segment can only overlap this range if it starts no earlier than
  // `minStart - MAX_SEGMENT_SPAN_MS` (its own duration is capped).
  const stored = await ctx.db
    .query("transcriptSegments")
    .withIndex("by_session_start", (q) =>
      q
        .eq("sessionId", sessionId)
        .gte("startMs", minStart - MAX_SEGMENT_SPAN_MS)
        .lte("startMs", maxEnd),
    )
    .take(MAX_OVERLAP_ROWS + 1);
  if (stored.length > MAX_OVERLAP_ROWS) {
    return null;
  }
  // Audio ranges are half-open: one window ending exactly where the next
  // begins is contiguous audio, not a duplicate. Strict bounds keep adjacent
  // windows (including a restart's first continuation) valid.
  return stored.some(
    (row) => row.speakerKey === speakerKey && row.startMs < maxEnd && row.endMs > minStart,
  );
}

/**
 * True when a batch with a restarted sequence is genuinely new audio: its
 * first `startMs` is strictly forward of the stored high-water mark and its
 * whole range overlaps nothing stored for this speaker. Replaying an earlier
 * window therefore fails even though its `seq` looks like a restart. Uniqueness
 * across a restart is enforced by this time ordering rather than by `seq`,
 * because the transcriber's counter genuinely began again at 1.
 */
async function isForwardSpeakerBatch(
  ctx: MutationCtx,
  sessionId: Id<"transcriptionSessions">,
  speakerKey: string,
  firstStartMs: number,
  lastStartMs: number,
  segments: readonly { readonly startMs: number; readonly endMs: number }[],
): Promise<boolean> {
  if (firstStartMs <= lastStartMs) {
    return false;
  }
  return (await storedSpeakerRangeOverlaps(ctx, sessionId, speakerKey, segments)) === false;
}

/**
 * Verifies that a batch whose sequence falls below the stored `lastSeq` is a
 * genuine late arrival rather than a replay. It must introduce sequence numbers
 * that were never stored and its session-relative time range must not overlap
 * any stored segment for the same speaker. Anything else is rejected exactly as
 * an out-of-order batch was before.
 */
async function assertLateSegmentBatch(
  ctx: MutationCtx,
  sessionId: Id<"transcriptionSessions">,
  speakerKey: string,
  segments: readonly { readonly seq: number; readonly startMs: number; readonly endMs: number }[],
): Promise<void> {
  for (const segment of segments) {
    const rows = await ctx.db
      .query("transcriptSegments")
      .withIndex("by_session_seq", (q) => q.eq("sessionId", sessionId).eq("seq", segment.seq))
      .take(MAX_REPLAY_SEQ_ROWS);
    if (rows.some((row) => row.speakerKey === speakerKey)) {
      throw new ConvexError("Segment sequence is out of order");
    }
  }
  const overlaps = await storedSpeakerRangeOverlaps(ctx, sessionId, speakerKey, segments);
  if (overlaps !== false) {
    // `true` is duplicated audio; `null` cannot be proven disjoint. Both fail
    // closed like any other out-of-order batch.
    throw new ConvexError("Segment sequence is out of order");
  }
}

async function resolveSpeakerName(ctx: MutationCtx, speakerKey: string): Promise<string> {
  const speaker = parseTranscriptionSpeakerKey(speakerKey);
  if (speaker === null) {
    return "Unknown speaker";
  }
  if (speaker.kind === "guest") {
    const session = await ctx.db.get(speaker.id as Id<"callGuestSessions">);
    if (session === null) {
      return "Guest";
    }
    return (await openGuestIdentity(session)).displayName;
  }
  const member = await ctx.db
    .query("members")
    .withIndex("by_user", (q) => q.eq("userId", speaker.id))
    .unique();
  if (member?.nickname !== undefined && member.nickname.trim().length > 0) {
    return member.nickname.trim();
  }
  const names = await accountNames(ctx, [speaker.id]);
  return names.get(speaker.id)?.trim() || "Participant";
}

/**
 * Records a transcriber heartbeat. The container posts roughly every minute;
 * only a stale row is written so a healthy service is not a hot document.
 */
export const recordServiceHello = internalMutation({
  args: {
    loadedModelId: v.optional(v.string()),
    loadedStatus: v.optional(v.union(v.literal("ready"), v.literal("not_installed"))),
    loadedError: v.optional(v.string()),
    /** True only while a model download is running; absent when idle. */
    downloadActive: v.optional(v.boolean()),
  },
  handler: async (ctx, args) => {
    const now = Date.now();
    const runtimeKnown = args.loadedStatus !== undefined;
    const runtimeReady =
      args.loadedStatus === "ready" &&
      args.loadedModelId !== undefined &&
      isTranscriptionModelId(args.loadedModelId);
    const status = await ctx.db
      .query("transcriberStatus")
      .withIndex("by_key", (q) => q.eq("key", "service"))
      .unique();
    if (status === null) {
      await ctx.db.insert("transcriberStatus", {
        key: "service",
        serviceSeenAt: now,
        ...(runtimeKnown ? { runtimeReady } : {}),
        ...(runtimeReady && args.loadedModelId !== undefined
          ? { runtimeModelId: args.loadedModelId }
          : {}),
      });
    } else {
      const patch: {
        serviceSeenAt?: number;
        runtimeReady?: boolean;
        runtimeModelId?: string | undefined;
      } = {
        ...(now - status.serviceSeenAt >= 30_000 ? { serviceSeenAt: now } : {}),
        ...(runtimeKnown ? { runtimeReady } : {}),
      };
      if (runtimeKnown) {
        // `undefined` clears the model id for a cold/not-installed runtime.
        patch.runtimeModelId =
          runtimeReady && args.loadedModelId !== undefined ? args.loadedModelId : undefined;
      }
      if (Object.keys(patch).length > 0) {
        await ctx.db.patch(status._id, patch);
      }
    }
    const config = await loadTranscriptionConfig(ctx);
    if (config === null) {
      return null;
    }
    // A restart after a lost/partial download only reports ready|not_installed.
    // Once the download has clearly stopped, release the Download button. A
    // hello that proves the configured model is actually loaded skips this and
    // reaches the ready re-sync below.
    const loadedMatchesConfig =
      args.loadedStatus === "ready" && args.loadedModelId === config.modelId;
    if (
      !loadedMatchesConfig &&
      args.downloadActive !== true &&
      config.modelStatus === "downloading" &&
      (config.modelUpdatedAt === undefined ||
        now - config.modelUpdatedAt >= TRANSCRIPTION_DOWNLOAD_STALE_MS)
    ) {
      await ctx.db.patch(config._id, {
        modelStatus: "error",
        modelProgress: undefined,
        modelError: "The download was interrupted",
        modelUpdatedAt: now,
      });
      return null;
    }
    if (
      args.loadedModelId === undefined ||
      !isTranscriptionModelId(args.loadedModelId) ||
      args.loadedStatus !== "ready"
    ) {
      return null;
    }
    // Never silently replace the owner's model. A fresh `not_installed` config
    // may adopt the restored model; otherwise only the same model may have its
    // status/error repaired.
    const isSameModel = config.modelId === args.loadedModelId;
    if (config.modelStatus !== "not_installed" && !isSameModel) {
      return null;
    }
    const nextError = args.loadedError?.slice(0, 300);
    if (
      config.modelId === args.loadedModelId &&
      config.modelStatus === "ready" &&
      config.modelError === nextError
    ) {
      return null;
    }
    await ctx.db.patch(config._id, {
      modelId: args.loadedModelId,
      modelStatus: "ready",
      modelProgress: 100,
      // A heartbeat without an error clears a stale download failure now that
      // the configured model is healthy again.
      modelError: nextError,
      modelUpdatedAt: now,
    });
    return null;
  },
});

/** Records a model install status posted by the transcriber. */
export const recordModelStatus = internalMutation({
  args: {
    modelId: v.string(),
    status: v.union(
      v.literal("not_installed"),
      v.literal("downloading"),
      v.literal("ready"),
      v.literal("error"),
    ),
    progress: v.optional(v.number()),
    error: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    if (!isTranscriptionModelId(args.modelId)) {
      return null;
    }
    const config = await loadTranscriptionConfig(ctx);
    if (config === null) {
      return null;
    }
    await ctx.db.patch(config._id, {
      modelId: args.modelId,
      modelStatus: args.status,
      // A missing percentage is indeterminate, and must clear any stale value
      // from the previous model instead of freezing at 100 or 0.
      modelProgress:
        args.progress !== undefined
          ? Math.min(100, Math.max(0, args.progress))
          : args.status === "ready"
            ? 100
            : undefined,
      ...(args.error !== undefined ? { modelError: args.error.slice(0, 300) } : {}),
      modelUpdatedAt: Date.now(),
    });
    return null;
  },
});

