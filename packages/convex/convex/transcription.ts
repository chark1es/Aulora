/**
 * A summary action that stops early (disabled addon, deleted session) must not
 * leave `pending` behind: the recovery cron only re-queues `none` or stale
 * pending rows.
 */
export const resetSummaryPending = internalMutation({
  args: {
    sessionId: v.id("transcriptionSessions"),
    attemptId: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const session = await ctx.db.get(args.sessionId);
    // A late abort from an older attempt must not clear a newer pending run.
    if (
      session === null ||
      session.summaryStatus !== "pending" ||
      session.summaryAttemptId !== args.attemptId
    ) {
      return null;
    }
    await ctx.db.patch(session._id, {
      summaryStatus: "none",
      summaryRequestedAt: undefined,
      summaryAttemptId: undefined,
    });
    return null;
  },
});

/** Internal action-facing config read. Includes the opened key; never public. */
export const configForAction = internalQuery({
  args: {
    userId: v.string(),
    baseUrl: v.optional(v.string()),
    apiKey: v.optional(v.string()),
    model: v.optional(v.string()),
    allowPrivateEndpoint: v.optional(v.boolean()),
  },
  handler: async (ctx, args) => {
    if (!(await userHasTranscriptFlag(ctx, args.userId, Permission.ManageTranscription))) {
      throw new ConvexError("Missing transcript permission");
    }
    if ((await listActiveBans(ctx, args.userId)).length > 0) {
      throw new ConvexError("You are banned from this workspace");
    }
    const config = await loadTranscriptionConfig(ctx);
    const storedKey =
      config?.apiKeyCiphertext === undefined
        ? ""
        : await openContent(
            { scope: "transcription.config", recordId: config._id },
            config.apiKeyCiphertext,
          );
    return {
      provider: config?.provider ?? "openrouter",
      baseUrl: args.baseUrl?.trim() || config?.baseUrl || OPENROUTER_BASE_URL,
      apiKey:
        args.apiKey !== undefined && args.apiKey.trim().length > 0 ? args.apiKey.trim() : storedKey,
      model: args.model?.trim() || config?.model || "",
      allowPrivateEndpoint: args.allowPrivateEndpoint ?? config?.allowPrivateEndpoint ?? false,
    };
  },
});

/** Summary input: session metadata plus one cursor page of decrypted segments. */
export const summaryInput = internalQuery({
  args: { sessionId: v.id("transcriptionSessions"), cursor: v.optional(v.string()) },
  handler: async (ctx, args) => {
    if (!(await transcriptionEnabled(ctx))) {
      return null;
    }
    const session = await ctx.db.get(args.sessionId);
    if (session === null) {
      return null;
    }
    const config = await loadTranscriptionConfig(ctx);
    const apiKey =
      config?.apiKeyCiphertext === undefined
        ? ""
        : await openContent(
            { scope: "transcription.config", recordId: config._id },
            config.apiKeyCiphertext,
          );
    const result = await ctx.db
      .query("transcriptSegments")
      .withIndex("by_session_start", (q) => q.eq("sessionId", args.sessionId))
      .order("asc")
      .paginate({ cursor: args.cursor ?? null, numItems: SEGMENT_PAGE_SIZE });
    const segments = [];
    for (const row of result.page) {
      const content = await segmentContent(row);
      segments.push({
        seq: row.seq,
        speakerName: content.speakerName,
        text: content.text,
        startMs: row.startMs,
        language: row.language ?? null,
      });
    }
    return {
      session: {
        id: session._id,
        language: null,
        segmentCount: session.segmentCount,
      },
      config: {
        provider: config?.provider ?? "openrouter",
        baseUrl: config?.baseUrl ?? OPENROUTER_BASE_URL,
        apiKey,
        model: config?.model ?? "",
        allowPrivateEndpoint: config?.allowPrivateEndpoint ?? false,
        summaryLanguage: config?.summaryLanguage ?? null,
        summaryStyle: config?.summaryStyle ?? null,
      },
      segments,
      nextCursor: result.isDone ? null : result.continueCursor,
    };
  },
});

/** Marks a summary ready or failed. Internal, called by the action. */
export const finishSummary = internalMutation({
  args: {
    sessionId: v.id("transcriptionSessions"),
    attemptId: v.optional(v.string()),
    status: v.union(v.literal("ready"), v.literal("error")),
    json: v.optional(v.string()),
    model: v.optional(v.string()),
    error: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const session = await ctx.db.get(args.sessionId);
    // Attempt B finished `ready`; a late failure from attempt A must not
    // overwrite it with `error`.
    if (session === null || session.summaryAttemptId !== args.attemptId) {
      return null;
    }
    const config = await loadTranscriptionConfig(ctx);
    const now = Date.now();
    await ctx.db.patch(session._id, {
      summaryStatus: args.status,
      summaryAttemptId: undefined,
      ...(args.json !== undefined
        ? { summaryCiphertext: await sealSummary(session._id, args.json) }
        : {}),
      ...(args.model !== undefined ? { summaryModel: args.model } : {}),
      summaryAt: now,
      ...(args.error !== undefined ? { summaryError: args.error.slice(0, 300) } : {}),
      ...(args.status === "error"
        ? { summaryError: (args.error ?? "Summary failed").slice(0, 300) }
        : {}),
      ...(session.retentionExpiresAt === undefined && session.endedAt !== undefined
        ? { retentionExpiresAt: retentionExpiry(session.endedAt, config?.retentionDays) }
        : {}),
    });
    return null;
  },
});

/**
 * Ends every active session in bounded batches. Used when an owner disables
 * the addon so the transcriber stops accepting audio immediately.
 */
export const stopAllActive = internalMutation({
  args: {},
  handler: async (ctx) => {
    const rows = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_status", (q) => q.eq("status", "active"))
      .take(20);
    const config = await loadTranscriptionConfig(ctx);
    const enabled = await transcriptionEnabled(ctx);
    const queued = enabled && summaryConfigured(config);
    const now = Date.now();
    for (const session of rows) {
      const attemptId = queued ? newSummaryAttemptId() : null;
      const totals = await speakerTotals(ctx, session._id);
      await ctx.db.patch(session._id, {
        status: "ended",
        endedAt: now,
        retentionExpiresAt: retentionExpiry(now, config?.retentionDays),
        // A disable must not hand the transcript to the LLM. If the addon is
        // re-enabled later, the normal `none` queue picks the session up.
        summaryStatus: attemptId === null ? "none" : "pending",
        ...(attemptId !== null
          ? { summaryRequestedAt: now, summaryAttemptId: attemptId }
          : { summaryAttemptId: undefined }),
        segmentCount: totals.segmentCount,
        lastSeq: Math.max(session.lastSeq, totals.lastSeq),
        countUpdatedAt: now,
      });
      const call = await ctx.db.get(session.callId);
      if (call !== null && call.transcriptionSessionId === session._id) {
        await ctx.db.patch(call._id, { transcriptionSessionId: undefined, updatedAt: now });
      }
      if (attemptId !== null) {
        await ctx.scheduler.runAfter(0, internal.transcriptionActions.summarize, {
          sessionId: session._id,
          attemptId,
        });
      }
    }
    // Disabling is immediate: an `ending` session must not keep its grace,
    // and no summary is queued while the addon is off.
    const endingRows = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_status", (q) => q.eq("status", "ending"))
      .take(20);
    for (const session of endingRows) {
      const totals = await speakerTotals(ctx, session._id);
      await ctx.db.patch(session._id, {
        status: "ended",
        endsAt: undefined,
        endedAt: session.endedAt ?? now,
        retentionExpiresAt:
          session.retentionExpiresAt ??
          retentionExpiry(session.endedAt ?? now, config?.retentionDays),
        summaryStatus: "none",
        summaryRequestedAt: undefined,
        summaryAttemptId: undefined,
        segmentCount: totals.segmentCount,
        lastSeq: Math.max(session.lastSeq, totals.lastSeq),
        countUpdatedAt: now,
      });
      const call = await ctx.db.get(session.callId);
      if (call !== null && call.transcriptionSessionId === session._id) {
        await ctx.db.patch(call._id, { transcriptionSessionId: undefined, updatedAt: now });
      }
    }
    if (rows.length === 20 || endingRows.length === 20) {
      await ctx.scheduler.runAfter(0, internal.transcription.stopAllActive, {});
    }
    return rows.length + endingRows.length;
  },
});

/**
 * Ended sessions that still need a summary, bounded per cron run. Also
 * recovers a `pending` row whose action died or returned early.
 */
export const sessionsNeedingSummary = internalMutation({
  args: {},
  handler: async (ctx) => {
    const now = Date.now();
    // Backstop for a lost per-session finalizer: finish due `ending` rows even
    // if their scheduled job did not run.
    const due = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_status", (q) => q.eq("status", "ending"))
      .take(20);
    for (const row of due) {
      if (row.endsAt !== undefined && row.endsAt <= now) {
        await finalizeEndingSession(ctx, row._id, now);
      }
    }
    if (!(await transcriptionEnabled(ctx))) {
      return 0;
    }
    const config = await loadTranscriptionConfig(ctx);
    if (!summaryConfigured(config)) {
      return 0;
    }
    const fresh = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_status_summary", (q) => q.eq("status", "ended").eq("summaryStatus", "none"))
      .take(20);
    const pending = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_status_summary", (q) => q.eq("status", "ended").eq("summaryStatus", "pending"))
      .take(20);
    const queued: Id<"transcriptionSessions">[] = [];
    for (const row of fresh) {
      const attemptId = newSummaryAttemptId();
      await ctx.db.patch(row._id, {
        summaryStatus: "pending",
        summaryRequestedAt: now,
        summaryAttemptId: attemptId,
      });
      await ctx.scheduler.runAfter(0, internal.transcriptionActions.summarize, {
        sessionId: row._id,
        attemptId,
      });
      queued.push(row._id);
    }
    for (const row of pending) {
      // Idempotent recovery: a live action refreshes this timestamp itself
      // only through the initial queue; ten minutes without finishing means
      // the job was lost.
      if (
        row.summaryRequestedAt !== undefined &&
        now - row.summaryRequestedAt < SUMMARY_PENDING_STALE_MS
      ) {
        continue;
      }
      const attemptId = newSummaryAttemptId();
      await ctx.db.patch(row._id, {
        summaryRequestedAt: now,
        summaryAttemptId: attemptId,
      });
      await ctx.scheduler.runAfter(0, internal.transcriptionActions.summarize, {
        sessionId: row._id,
        attemptId,
      });
      queued.push(row._id);
    }
    return queued.length;
  },
});

/** Purges transcripts whose retention window elapsed. */
export const purgeExpired = internalMutation({
  args: {},
  handler: async (ctx) => {
    const now = Date.now();
    const expired = await ctx.db
      .query("transcriptionSessions")
      // `undefined` sorts before every number in an index, so a missing expiry
      // (an active session or retention 0 = keep forever) would otherwise match
      // `lt(now)` and be purged. The lower bound excludes it.
      .withIndex("by_retention", (q) => q.gt("retentionExpiresAt", 0).lt("retentionExpiresAt", now))
      .take(5);
    for (const session of expired) {
      await ctx.db.delete(session._id);
      await ctx.scheduler.runAfter(0, internal.transcriptionCleanup.deleteSegments, {
        sessionId: session._id,
      });
    }
    if (expired.length >= 5) {
      await ctx.scheduler.runAfter(0, internal.transcription.purgeExpired, {});
    }
    return expired.length;
  },
});
