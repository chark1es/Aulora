/**
 * The optional transcription addon (`api.transcription.*`).
 *
 * The server never sees call audio: each participant streams its own mic to the
 * optional transcriber container, which posts finished segments back over the
 * shared-secret HTTP ingest route. Convex only stores sealed text and controls
 * who may start, read and delete it.
 */

/** True when the deployment has the transcriber's shared secret. */
function transcriberConfigured(): boolean {
  const secret = process.env.TRANSCRIBER_TOKEN;
  return secret !== undefined && secret.length > 0;
}

/**
 * True when the shared secret exists *and* the container has reported within
 * the stale window. The secret alone is always generated by setup, so it says
 * nothing about whether the optional profile is actually running.
 */
async function transcriberServiceInstalled(ctx: QueryCtx): Promise<boolean> {
  if (!transcriberConfigured()) {
    return false;
  }
  const status = await ctx.db
    .query("transcriberStatus")
    .withIndex("by_key", (q) => q.eq("key", "service"))
    .unique();
  return status !== null && Date.now() - status.serviceSeenAt <= TRANSCRIPTION_SERVICE_STALE_MS;
}

/** Whether the addon is available to this caller, without leaking config. */
export const status = query({
  args: {},
  handler: async (ctx) => {
    const { userId } = await requireAuth(ctx);
    const server = await ctx.db.query("server").first();
    const config = await loadTranscriptionConfig(ctx);
    await loadPermissionContext(ctx, userId);
    return {
      enabled: server?.settings.transcriptionEnabled === true,
      modelId: config?.modelId ?? null,
      modelStatus: config?.modelStatus ?? "not_installed",
      modelProgress: config?.modelProgress ?? null,
      ready: config?.modelStatus === "ready",
      // Whether the running container actually has an engine loaded, separate
      // from the owner's selected/downloaded model.
      runtimeReady: await transcriberRuntimeReady(ctx),
      retentionDays: config?.retentionDays ?? 30,
      serviceInstalled: await transcriberServiceInstalled(ctx),
    };
  },
});

