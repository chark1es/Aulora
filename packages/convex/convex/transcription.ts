/** Saves transcription configuration. Requires `ManageTranscription`. */
export const updateConfig = mutation({
  args: {
    provider: v.optional(v.union(v.literal("openrouter"), v.literal("openai_compatible"))),
    baseUrl: v.optional(v.string()),
    /** Empty string clears the stored key; omit to keep it. */
    apiKey: v.optional(v.string()),
    model: v.optional(v.string()),
    summaryLanguage: v.optional(v.string()),
    summaryStyle: v.optional(v.string()),
    retentionDays: v.optional(v.number()),
    allowPrivateEndpoint: v.optional(v.boolean()),
  },
  handler: async (ctx, args) => {
    const { userId } = await requireWorkspaceContext(ctx, Permission.ManageTranscription);
    await assertMayParticipate(ctx, userId);
    const existing = await loadTranscriptionConfig(ctx);
    const now = Date.now();
    const provider: TranscriptionProvider = args.provider ?? existing?.provider ?? "openrouter";
    const baseUrl = (args.baseUrl ?? existing?.baseUrl ?? OPENROUTER_BASE_URL).trim();
    if (baseUrl.length === 0 || baseUrl.length > 500) {
      throw new ConvexError("The summary endpoint must be a valid URL");
    }
    const model = (args.model ?? existing?.model ?? "").trim();
    if (model.length > 200) {
      throw new ConvexError("The summary model name is too long");
    }
    const retentionDays = clampRetentionDays(args.retentionDays ?? existing?.retentionDays ?? 30);
    const summaryLanguage = args.summaryLanguage ?? existing?.summaryLanguage ?? "";
    const summaryStyle = args.summaryStyle ?? existing?.summaryStyle ?? "";
    if (summaryLanguage.length > 40 || summaryStyle.length > 200) {
      throw new ConvexError("Summary options are too long");
    }
    const allowPrivateEndpoint =
      args.allowPrivateEndpoint ?? existing?.allowPrivateEndpoint ?? false;
    const keyPlain =
      args.apiKey === undefined
        ? undefined
        : args.apiKey.trim().length === 0
          ? ""
          : args.apiKey.trim();
    if (existing === null) {
      const id = await ctx.db.insert("transcriptionConfig", {
        modelId: "base",
        modelStatus: "not_installed",
        provider,
        baseUrl,
        model,
        retentionDays,
        allowPrivateEndpoint,
        updatedAt: now,
        updatedBy: userId,
        ...(summaryLanguage.trim().length > 0 ? { summaryLanguage: summaryLanguage.trim() } : {}),
        ...(summaryStyle.trim().length > 0 ? { summaryStyle: summaryStyle.trim() } : {}),
      });
      if (keyPlain !== undefined && keyPlain.length > 0) {
        await ctx.db.patch(id, {
          apiKeyCiphertext: await sealString(
            { scope: "transcription.config", recordId: id },
            keyPlain,
          ),
        });
      }
      await writeAudit(ctx, {
        actorId: userId,
        action: "transcription.updateConfig",
        targetId: id,
        meta: JSON.stringify({ provider, retentionDays, allowPrivateEndpoint }),
      });
      return null;
    }
    const sealedKey =
      keyPlain === undefined
        ? undefined
        : keyPlain.length === 0
          ? null
          : await sealString({ scope: "transcription.config", recordId: existing._id }, keyPlain);
    await ctx.db.patch(existing._id, {
      provider,
      baseUrl,
      model,
      retentionDays,
      summaryLanguage: summaryLanguage.trim().length > 0 ? summaryLanguage.trim() : undefined,
      summaryStyle: summaryStyle.trim().length > 0 ? summaryStyle.trim() : undefined,
      allowPrivateEndpoint,
      ...(sealedKey === undefined
        ? {}
        : sealedKey === null
          ? { apiKeyCiphertext: undefined }
          : { apiKeyCiphertext: sealedKey }),
      updatedAt: now,
      updatedBy: userId,
    });
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.updateConfig",
      targetId: existing._id,
      meta: JSON.stringify({ provider, retentionDays, allowPrivateEndpoint }),
    });
    return null;
  },
});

/** Asks the transcriber to download an allowlisted model into its volume. */
export const downloadModel = mutation({
  args: { modelId: v.string() },
  handler: async (ctx, args) => {
    await requireTranscriptionAddon(ctx);
    const { userId } = await requireWorkspaceContext(ctx, Permission.ManageTranscription);
    await assertMayParticipate(ctx, userId);
    if (!isTranscriptionModelId(args.modelId)) {
      throw new ConvexError("That model is not available");
    }
    if (process.env.TRANSCRIBER_TOKEN === undefined || process.env.TRANSCRIBER_TOKEN.length === 0) {
      throw new ConvexError("Transcription service not installed");
    }
    const existing = await loadTranscriptionConfig(ctx);
    const now = Date.now();
    if (existing === null) {
      await ctx.db.insert("transcriptionConfig", {
        modelId: args.modelId,
        modelStatus: "downloading",
        // No fake 0%: the view reports `progress: null` until a real value
        // arrives (or ready reports 100).
        modelUpdatedAt: now,
        provider: "openrouter",
        baseUrl: OPENROUTER_BASE_URL,
        model: "",
        retentionDays: 30,
        allowPrivateEndpoint: false,
        updatedAt: now,
        updatedBy: userId,
      });
    } else {
      await ctx.db.patch(existing._id, {
        modelId: args.modelId,
        modelStatus: "downloading",
        modelProgress: undefined,
        modelError: undefined,
        modelUpdatedAt: now,
      });
    }
    await ctx.scheduler.runAfter(0, internal.transcriptionActions.requestModelDownload, {
      modelId: args.modelId,
    });
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.downloadModel",
      targetId: args.modelId,
    });
    return null;
  },
});

/** Starts transcription in a call the caller is in. */
export const start = mutation({
  args: { callId: v.id("calls") },
  handler: async (ctx, args) => {
    await requireTranscriptionAddon(ctx);
    const { userId } = await requireWorkspaceContext(ctx, Permission.StartTranscription);
    await assertMayParticipate(ctx, userId);
    const call = await ctx.db.get(args.callId);
    if (call === null || call.status === "ended") {
      throw new ConvexError("This call has ended");
    }
    await requireCallSeat(ctx, call, userId);
    const config = await loadTranscriptionConfig(ctx);
    if (config?.modelStatus !== "ready") {
      throw new ConvexError("Download a speech model before starting transcription");
    }
    if (!(await transcriberServiceInstalled(ctx))) {
      throw new ConvexError(
        "The transcription service is not running; start the transcriber container",
      );
    }
    if (!(await transcriberRuntimeReady(ctx))) {
      // The owner's config may say ready while a restarted (or empty) container
      // has no engine loaded. Start must not mint a token that closes 4503.
      throw new ConvexError(
        "The transcription service has no model loaded; download a model or restart the transcriber",
      );
    }
    if ((await activeSessionForCall(ctx, call._id)) !== null) {
      throw new ConvexError("Transcription is already running in this call");
    }
    const finalizing = await ctx.db
      .query("transcriptionSessions")
      .withIndex("by_call_status", (q) => q.eq("callId", call._id).eq("status", "ending"))
      .first();
    if (finalizing !== null || call.transcriptionSessionId !== undefined) {
      throw new ConvexError("Transcription is already running in this call");
    }
    const now = Date.now();
    const sessionId = await ctx.db.insert("transcriptionSessions", {
      callId: call._id,
      ...(call.channelId !== undefined ? { channelId: call.channelId } : {}),
      startedBy: userId,
      startedAt: now,
      status: "active",
      summaryStatus: "none",
      segmentCount: 0,
      lastSeq: 0,
    });
    // Remember everyone seated at start so a final drain during `ending` is
    // accepted even after the participant leaves.
    const seats = await ctx.db
      .query("callParticipants")
      .withIndex("by_call", (q) => q.eq("callId", call._id))
      .take(64);
    for (const seat of seats) {
      const speakerKey =
        seat.guestId !== undefined
          ? transcriptionSpeakerKey("guest", seat.guestId)
          : transcriptionSpeakerKey("user", seat.userId);
      await authorizeTranscriptionSpeaker(ctx, sessionId, speakerKey);
    }
    await ctx.db.patch(call._id, { transcriptionSessionId: sessionId, updatedAt: now });
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.start",
      targetId: sessionId,
      meta: JSON.stringify({ callId: call._id }),
    });
    return { sessionId };
  },
});

async function requireCallSeat(
  ctx: QueryCtx | MutationCtx,
  call: Doc<"calls">,
  userId: string,
): Promise<void> {
  if (call.channelId !== undefined) {
    await requireChannelAccessForUser(ctx, userId, call.channelId, Permission.Connect);
  }
  const row = await ctx.db
    .query("callParticipants")
    .withIndex("by_call_user", (q) => q.eq("callId", call._id).eq("userId", userId))
    .unique();
  if (row === null || row.guestId !== undefined) {
    throw new ConvexError("You are not in this call");
  }
}

/** Stops an active session. The starter, a seated member or a manager may. */
export const stop = mutation({
  args: { sessionId: v.id("transcriptionSessions") },
  handler: async (ctx, args) => {
    // Stopping must work even after the addon is disabled: it is the way to
    // clean up a session that was still running when the owner turned it off.
    const { userId } = await requireWorkspaceContext(ctx);
    const session = await ctx.db.get(args.sessionId);
    if (session === null) {
      throw new ConvexError("Transcription session not found");
    }
    if (session.status !== "active") {
      return null;
    }
    const context = await loadPermissionContext(ctx, userId);
    const permissions = workspacePermissions(context);
    const manager = hasPermission(permissions, Permission.ManageTranscription);
    const starter = session.startedBy === userId;
    if (!manager && !starter) {
      if (!hasPermission(permissions, Permission.StartTranscription)) {
        throw new ConvexError("Missing transcript permission");
      }
      const call = await ctx.db.get(session.callId);
      if (call === null) {
        throw new ConvexError("This call has ended");
      }
      await requireCallSeat(ctx, call, userId);
    }
    await assertMayParticipate(ctx, userId);
    // The transcriber may still be transcribing its final window. Enter the
    // bounded finalization window; the summary is queued only after it closes.
    await beginTranscriptionFinalize(ctx, session);
    await writeAudit(ctx, {
      actorId: userId,
      action: "transcription.stop",
      targetId: session._id,
    });
    return null;
  },
});

/**
 * Finalizes one `ending` session once its grace has elapsed. Idempotent: a
 * concurrent scheduler job or cron backstop re-reads the row and no-ops if it
 * has already ended.
 */
async function finalizeEndingSession(
  ctx: MutationCtx,
  sessionId: Id<"transcriptionSessions">,
  now: number,
): Promise<boolean> {
  const session = await ctx.db.get(sessionId);
  if (session === null || session.status !== "ending") {
    return false;
  }
  if (session.endsAt !== undefined && now < session.endsAt) {
    return false;
  }
  const config = await loadTranscriptionConfig(ctx);
  const enabled = await transcriptionEnabled(ctx);
  const queued = enabled && summaryConfigured(config);
  const attemptId = queued ? newSummaryAttemptId() : null;
  const totals = await speakerTotals(ctx, session._id);
  const endedAt = session.endedAt ?? now;
  await ctx.db.patch(session._id, {
    status: "ended",
    endsAt: undefined,
    endedAt,
    retentionExpiresAt:
      session.retentionExpiresAt ?? retentionExpiry(endedAt, config?.retentionDays),
    // The summary is queued here, only after the finalization window closed.
    summaryStatus: queued ? "pending" : "none",
    ...(attemptId !== null
      ? { summaryRequestedAt: now, summaryAttemptId: attemptId }
      : { summaryRequestedAt: undefined, summaryAttemptId: undefined }),
    segmentCount: totals.segmentCount,
    lastSeq: Math.max(session.lastSeq, totals.lastSeq),
    countUpdatedAt: now,
  });
  const call = await ctx.db.get(session.callId);
  if (call !== null && call.transcriptionSessionId === session._id) {
    await ctx.db.patch(call._id, { transcriptionSessionId: undefined, updatedAt: now });
  }
  if (attemptId !== null) {
    await ctx.scheduler.runAfter(0, internal.transcriptionActions.summarize, {
      sessionId: session._id,
      attemptId,
    });
  }
  return true;
}

/** Scheduled once per session by `beginTranscriptionFinalize`. */
export const finalizeSession = internalMutation({
  args: { sessionId: v.id("transcriptionSessions") },
  handler: async (ctx, args) => {
    await finalizeEndingSession(ctx, args.sessionId, Date.now());
    return null;
  },
});

/** Mints a short-lived transcriber token bound to the caller's own audio. */
export const mintAudioTokenForCall = mutation({
  args: { sessionId: v.id("transcriptionSessions") },
  handler: async (ctx, args) => {
    await requireTranscriptionAddon(ctx);
    const { userId } = await requireAuth(ctx);
    await assertMayParticipate(ctx, userId);
    const session = await ctx.db.get(args.sessionId);
    if (session === null || session.status !== "active") {
      throw new ConvexError("Transcription is not running");
    }
    const call = await ctx.db.get(session.callId);
    if (call === null || call.status === "ended") {
      throw new ConvexError("This call has ended");
    }
    await requireCallSeat(ctx, call, userId);
    const secret = process.env.TRANSCRIBER_TOKEN;
    if (secret === undefined || secret.length === 0) {
      throw new ConvexError("Transcription service not installed");
    }
    const speakerKey = transcriptionSpeakerKey("user", userId);
    await authorizeTranscriptionSpeaker(ctx, session._id, speakerKey);
    const minted = await mintAudioToken(secret, {
      sid: session._id,
      cid: call._id,
      sub: speakerKey,
      start: session.startedAt,
    });
    return {
      token: minted.token,
      expiresAt: minted.expiresAt,
      sessionId: session._id,
      wsPath: "/transcribe/",
    };
  },
});

